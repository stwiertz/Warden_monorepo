// Story 12.2 (Epic 12) — GPU detection-engine Expo config plugin.
//
// AC0a verdict: **Option A** (Stephane, 2026-09-15). The engine Kotlin lives in
// `apps/mobile` and is emitted by this plugin, modelled on the 390-line
// with-foreground-service.js (Story 1.2). Rationale: architecture.md:2190
// amendment 5g names exactly this ("Story 12.2 introduces a GLES 3.0 +
// MediaCodec engine module… MUST obey… sole access via `shared/services/*.ts`");
// it measures inside the shipped app's real minSdk/ABI/gradle reality, which is
// the only honest reference-device number; Story 12.4 inherits the plumbing; and
// a 12.3 rejection costs one plugin file + one app.json line.
//
// AC18a — `apps/mobile/android/` is GITIGNORED and regenerated by
// `expo prebuild`. Every durable native artifact MUST be emitted here. A
// hand-edit of the generated tree is erased by the next `--clean` and is
// invisible to git.
//
// What it emits:
//   1. `assets/keyframe_engine_bench.frag` — the shader, COPIED VERBATIM from
//      the tooling source of truth, guarded by a checksum (AC4).
//   2. Six RN-agnostic Kotlin sources implementing the engine, the LUT packer,
//      the keyframe decoder, the CPU baseline and the bench harness.
//   3. A thin RN bridge (module + ReactPackage) — the trigger only; no engine
//      logic lives in it, so the measurement code and the future runtime module
//      are the same code (AC0a's closing clause).
//   4. A DEBUG-ONLY `<activity>` in `src/debug/AndroidManifest.xml` so the bench
//      is adb-triggerable without an exported activity ever reaching a release
//      manifest.
//
// Android-only by construction (amendment 5c): `withDangerousMod("android")` and
// `withMainApplication` no-op on iOS.

const {
  withAppBuildGradle,
  withDangerousMod,
  withMainApplication,
  withPlugins,
  withRunOnce,
} = require("@expo/config-plugins");
const crypto = require("crypto");
const fs = require("fs");
const path = require("path");

const PACKAGE = "team.warden.mobile";
const PACKAGE_PATH = PACKAGE.split(".").join("/");

// ---------------------------------------------------------------------------
// AC4 — ONE GLSL body, two dialects, byte-identical apart from the preamble.
//
// The shader is NOT re-authored here as a JS string; it is READ FROM the tooling
// package and copied verbatim, which is what makes "the Android copy is
// regenerated from it" a mechanical fact rather than a promise. The checksum is
// taken over LF-NORMALIZED bytes so a CRLF checkout (Windows) and an LF checkout
// (CI/Linux) agree — the guard must fail on a CONTENT change, never on a line
// ending.
//
// If the tooling `.frag` legitimately changes, AC4's procedure is: change it in
// the tooling file first, re-gate BOTH dialects
// (`uv run python -m tools.keyframe_engine_bench --gate-glsl`), re-run the
// tooling pytest suite, then update FRAG_SHA256 here. Prebuild failing loudly is
// the point: silent drift between the PC reference and the device port would
// invalidate every parity number the story produces.
// ---------------------------------------------------------------------------
const FRAG_RELATIVE_PATH = path.join(
  "..",
  "..",
  "tooling",
  "tools",
  "keyframe_engine_bench",
  "keyframe_engine_bench.frag"
);
const FRAG_SHA256 =
  "5bc4fc754fb592d81209fe6a512e21b11e3ec3bedd36fc3f5148eba29ffdeee0";
const FRAG_ASSET_NAME = "keyframe_engine_bench.frag";

function readVerbatimFrag() {
  // `__dirname` is apps/mobile/plugins — the tooling package is a sibling app in
  // the same pnpm workspace, so this resolves in every checkout of the monorepo.
  const src = path.resolve(__dirname, FRAG_RELATIVE_PATH);
  if (!fs.existsSync(src)) {
    throw new Error(
      `[with-detection-engine] AC4: shader source of truth not found at ${src}. ` +
        "The Android shader is a verbatim copy of the tooling file — it is never " +
        "re-authored. Restore apps/tooling/tools/keyframe_engine_bench/."
    );
  }
  const normalized = fs.readFileSync(src).toString("utf8").replace(/\r\n/g, "\n");
  const actual = crypto.createHash("sha256").update(normalized, "utf8").digest("hex");
  if (actual !== FRAG_SHA256) {
    throw new Error(
      "[with-detection-engine] AC4 VIOLATION — keyframe_engine_bench.frag has " +
        `changed.\n  expected sha256 (LF-normalized): ${FRAG_SHA256}\n` +
        `  actual   sha256 (LF-normalized): ${actual}\n` +
        "A change to the shader body invalidates every parity number Story 12.2 " +
        "measured against the PC reference. AC4's procedure: change the TOOLING " +
        "file first, re-gate both dialects (--gate-glsl), re-run the tooling " +
        "pytest suite, then update FRAG_SHA256 in this plugin. Do not 'fix' this " +
        "by editing the checksum alone."
    );
  }
  return normalized;
}

// ---------------------------------------------------------------------------
// Kotlin sources. Each is read from `plugins/kotlin/` rather than inlined as a
// template literal: the FGS plugin's string-template approach works for ~100
// lines, but the engine is ~1500 lines of Kotlin across six files and embedding
// that in JS string literals makes `$` interpolation a live hazard (GLSL and
// Kotlin both use `$`) and defeats every editor's Kotlin tooling.
// ---------------------------------------------------------------------------
const KOTLIN_SOURCE_DIR = path.resolve(__dirname, "kotlin");
const KOTLIN_FILES = [
  "WardenGlUtil.kt",
  "WardenRulePacker.kt",
  "WardenDetectionEngine.kt",
  "WardenCpuBaseline.kt",
  "WardenKeyframeDecoder.kt",
  "WardenEngineBench.kt",
  "WardenDetectionEngineModule.kt",
  "WardenDetectionEnginePackage.kt",
  "WardenEngineBenchActivity.kt",
];

function withEngineSources(config) {
  return withDangerousMod(config, [
    "android",
    (config) => {
      const androidRoot = config.modRequest.platformProjectRoot;

      // withDangerousMod runs BEFORE the other modifiers and Expo documents its
      // ordering as unreliable, so never assume a directory exists.
      const javaDir = path.join(
        androidRoot,
        "app",
        "src",
        "main",
        "java",
        PACKAGE_PATH
      );
      fs.mkdirSync(javaDir, { recursive: true });
      for (const name of KOTLIN_FILES) {
        const src = path.join(KOTLIN_SOURCE_DIR, name);
        if (!fs.existsSync(src)) {
          throw new Error(
            `[with-detection-engine] missing Kotlin source ${src}. The plugin ` +
              "emits the engine from apps/mobile/plugins/kotlin/ — that directory " +
              "is the tracked source; android/ is a build artifact."
          );
        }
        fs.copyFileSync(src, path.join(javaDir, name));
      }

      // 🔴 REVIEW 2026-09-15: sweep Warden*.kt files that are no longer in
      // KOTLIN_FILES. Nothing removed them before, so renaming or dropping a
      // source left the old .kt behind on a reused android/ tree (prebuild
      // without --clean) and the build failed with a duplicate-class error
      // pointing at a file the tracked sources no longer contain. The FGS
      // plugin's own files are left alone — only names this plugin owns.
      const owned = new Set(KOTLIN_FILES);
      for (const existing of fs.readdirSync(javaDir)) {
        if (!/^Warden(DetectionEngine|Engine|GlUtil|RulePacker|CpuBaseline|KeyframeDecoder).*\.kt$/.test(existing)) {
          continue;
        }
        if (owned.has(existing)) continue;
        fs.rmSync(path.join(javaDir, existing));
      }

      // AC0d — the `.frag` lands in `assets/`, NOT `res/raw/`. `res/raw/`
      // resource names may not contain uppercase letters or dots, so the file
      // would have to be RENAMED to live there — which directly undercuts AC4's
      // "copied verbatim" guarantee and the one-source-of-truth claim. `assets/`
      // preserves the filename and is read with AssetManager.open().
      const assetsDir = path.join(androidRoot, "app", "src", "main", "assets");
      fs.mkdirSync(assetsDir, { recursive: true });
      fs.writeFileSync(
        path.join(assetsDir, FRAG_ASSET_NAME),
        readVerbatimFrag(),
        "utf8"
      );

      // AC7/AC5 — the packed reference LUT and the PC parity fixtures are pushed
      // at run time via adb, never baked into the APK: they are gitignored
      // build outputs (map_config.v2.json, the 2666-PNG corpus) and an APK is
      // the wrong transport for 2.3 GB of capture.
      return config;
    },
  ]);
}

// ---------------------------------------------------------------------------
// Bench entry point — DEBUG MANIFEST ONLY.
//
// The bench must be triggerable headlessly (`adb shell am start`), which needs an
// exported component. Declaring one in the MAIN manifest would ship an exported
// activity in every release build for the sake of a spike, so it is written into
// `src/debug/AndroidManifest.xml` instead: the manifest merger adds it to debug
// variants only and the release manifest never sees it. The activity ALSO gates
// itself on BuildConfig.DEBUG at runtime (belt and braces — a manifest overlay is
// easy to get wrong and this costs one line).
//
// `src/debug/AndroidManifest.xml` is itself prebuild-generated, so this is a
// patch-with-anchor, following the FGS precedent of throwing loudly on drift.
// ---------------------------------------------------------------------------
// NOTE: an XML comment may not contain a double hyphen ANYWHERE (XML 1.0 §2.5),
// so the `adb shell am start` invocation — which is all `--es` flags — cannot be
// written here. The manifest merger's error for this is a bare
// "Error parsing AndroidManifest.xml" with no line number. The trigger command
// lives in WardenEngineBenchActivity's KDoc instead.
const BENCH_ACTIVITY_XML =
  '        <!-- Story 12.2 — GPU engine bench harness (with-detection-engine.js).\n' +
  "             DEBUG-ONLY by construction: this overlay is never merged into a\n" +
  "             release manifest. See WardenEngineBenchActivity for the adb\n" +
  "             trigger command. -->\n" +
  // The activity deliberately STAYS ON SCREEN for the duration of the run.
  //
  // `Theme.NoDisplay` is not usable here: Android requires a NoDisplay activity
  // to call finish() before onResume() completes, and this one returns
  // immediately while a worker thread runs for minutes ("did not call finish()
  // prior to onResume() completing" -> FATAL). Beyond legality, a visible
  // foreground activity keeps the process at foreground importance for the whole
  // measurement, which matters for a multi-minute run: a backgrounded process is
  // subject to both the low-memory killer and a different CPU/GPU governor
  // policy, and AC11 asks for thermal/sustained-clock context that a
  // deprioritised process would quietly distort.
  '        <activity android:name=".WardenEngineBenchActivity"\n' +
  '            android:exported="true"\n' +
  '            android:excludeFromRecents="true"\n' +
  '            android:label="Warden 12.2 bench" />\n';

function withBenchActivity(config) {
  return withDangerousMod(config, [
    "android",
    (config) => {
      const debugManifest = path.join(
        config.modRequest.platformProjectRoot,
        "app",
        "src",
        "debug",
        "AndroidManifest.xml"
      );
      // The debug overlay is only laid down when prebuild copies a FRESH
      // template; on a reused android/ tree it may be absent. It is ours to own,
      // so create a minimal one rather than failing — the bench activity must
      // never be relocated to the main manifest, which would ship an exported
      // component in every release build.
      if (!fs.existsSync(debugManifest)) {
        fs.mkdirSync(path.dirname(debugManifest), { recursive: true });
        fs.writeFileSync(
          debugManifest,
          '<manifest xmlns:android="http://schemas.android.com/apk/res/android"\n' +
            '    xmlns:tools="http://schemas.android.com/tools">\n' +
            "    <application />\n" +
            "</manifest>\n",
          "utf8"
        );
      }
      let xml = fs.readFileSync(debugManifest, "utf8");
      // Idempotent by REPLACEMENT, not by presence.
      //
      // Skipping when the activity name is already there makes the plugin
      // unable to CHANGE the declaration on a reused android/ tree: an edit here
      // would silently never reach the APK, and the next build would keep
      // whatever the first prebuild happened to write. (That is exactly how a
      // stale `Theme.NoDisplay` survived a plugin fix during 12.2 development
      // and kept crashing the bench.) Strip our previous block, then re-emit.
      //
      // REVIEW 2026-09-15: a single non-global replace also left a stale block
      // behind whenever the previous prebuild CRASHED mid-write (our comment
      // present, the closing `/>` never written) or had already emitted two —
      // producing a duplicate <activity> or a malformed comment, which surfaces
      // as the manifest merger's opaque "Error parsing AndroidManifest.xml" with
      // no line number. Strip EVERY block we own, and refuse to proceed on a
      // half-written one rather than appending next to it.
      const strayOpen = /[ \t]*<!-- Story 12\.2(?![\s\S]*?WardenEngineBenchActivity"[\s\S]*?\/>)/;
      if (strayOpen.test(xml)) {
        throw new Error(
          "[with-detection-engine] the debug manifest overlay contains a Story 12.2 " +
            "comment with no matching <activity .../> — a previous prebuild was " +
            "interrupted mid-write. Delete android/app/src/debug/AndroidManifest.xml " +
            "(it is generated) and re-run prebuild."
        );
      }
      xml = xml.replace(
        /[ \t]*<!-- Story 12\.2[\s\S]*?WardenEngineBenchActivity"[\s\S]*?\/>\n/g,
        ""
      );
      // The template's <application/> is self-closing; expand it so children fit.
      const selfClosing = /<application([^>]*?)\/>/;
      if (selfClosing.test(xml)) {
        xml = xml.replace(
          selfClosing,
          (_m, attrs) => `<application${attrs}>\n${BENCH_ACTIVITY_XML}    </application>`
        );
      } else if (xml.includes("</application>")) {
        xml = xml.replace("</application>", `${BENCH_ACTIVITY_XML}    </application>`);
      } else {
        throw new Error(
          "[with-detection-engine] could not find an <application> element in the " +
            "debug manifest overlay — Expo prebuild template shape changed; update " +
            "the plugin."
        );
      }
      fs.writeFileSync(debugManifest, xml, "utf8");
      return config;
    },
  ]);
}

// ---------------------------------------------------------------------------
// Register WardenDetectionEnginePackage() in MainApplication.kt getPackages().
// Same anchor-patch precedent as the FGS plugin, and it THROWS on drift for the
// same reason: a silently-skipped registration would present as "the native
// module is null" at run time, three layers away from the cause.
// ---------------------------------------------------------------------------
const PACKAGE_MARKER =
  "// Story 12.2 — GPU detection engine bridge (with-detection-engine.js)";

function withPackageRegistration(config) {
  return withMainApplication(config, (config) => {
    let src = config.modResults.contents;
    // Idempotent by REPLACEMENT, not by presence — the same rule withBenchActivity
    // follows, and for the same measured reason.
    //
    // 🔴 REVIEW 2026-09-15: this used to early-return on
    // `src.includes("WardenDetectionEnginePackage()")`. That is idempotency by
    // PRESENCE, which this very delivery records as shipped bug #2: on a reused
    // android/ tree (prebuild without --clean) any CHANGE to the registration —
    // a second add(), a corrected indent, a different anchor — would no-op
    // silently, and the APK would keep whatever the first prebuild wrote, with
    // no error at any stage. Strip our block, then re-emit it.
    src = src.replace(
      new RegExp(`[ \\t]*${escapeRegExp(PACKAGE_MARKER)}\\n[ \\t]*add\\(WardenDetectionEnginePackage\\(\\)\\)\\n`, "g"),
      ""
    );
    const anchor = "// add(MyReactNativePackage())";
    if (!src.includes(anchor)) {
      throw new Error(
        "[with-detection-engine] could not find the autolink anchor in " +
          "MainApplication.kt — Expo SDK MainApplication shape changed; update the " +
          "plugin."
      );
    }
    src = src.replace(
      anchor,
      `${anchor}\n              ${PACKAGE_MARKER}\n              add(WardenDetectionEnginePackage())`
    );
    config.modResults.contents = src;
    return config;
  });
}

function escapeRegExp(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

// ---------------------------------------------------------------------------
// AC0b Option C — the ffmpeg-kit decode control.
//
// `@wokcito/ffmpeg-kit-react-native` is ALREADY a mobile dependency
// (apps/mobile/package.json:26) and its android module declares
// `implementation 'io.github.jamaismagic.ffmpeg:ffmpeg-kit-main-16kb:6.1.4'`.
// `implementation` is NOT transitive at COMPILE time, so `com.arthenica.ffmpegkit`
// is present in the APK at run time but invisible to our Kotlin. Declaring the
// SAME coordinate here (same version — no resolution conflict) makes the control
// compile without adding anything to the shipped artifact.
//
// The control runs 12.1's LITERAL `-skip_frame nokey` on device. It is software
// decode and WILL lose to MediaCodec; that is the point — it isolates "is
// MediaCodec hardware decode actually faster" from every other variable and
// gives 12.3 a directly comparable decode number.
// ---------------------------------------------------------------------------
const FFMPEG_KIT_COORDINATE =
  "io.github.jamaismagic.ffmpeg:ffmpeg-kit-main-16kb:6.1.4";
const FFMPEG_KIT_MARKER = "// Story 12.2 — AC0b Option C decode control";

function withFfmpegKitCompileDep(config) {
  return withAppBuildGradle(config, (config) => {
    let src = config.modResults.contents;
    // Idempotent by REPLACEMENT — see withPackageRegistration. A presence check
    // here meant a bump to FFMPEG_KIT_COORDINATE never reached a reused
    // android/ tree, surfacing only as `available: false` plus a
    // ClassNotFoundException string, which reads as "the dep was dropped".
    src = src.replace(
      new RegExp(`[ \\t]*${escapeRegExp(FFMPEG_KIT_MARKER)}\\n[ \\t]*implementation '[^']*'\\n`, "g"),
      ""
    );
    // 🔴 Anchor on the APP dependencies block specifically.
    //
    // REVIEW 2026-09-15: this used to take the FIRST `dependencies {` in the
    // file. A template (or a preceding config plugin) emitting
    // `buildscript { dependencies { … } }`, or the literal inside a comment,
    // would put our `implementation` in the wrong scope — a Gradle configuration
    // failure at best, a silently non-applied dependency at worst. The Expo app
    // template's own block is preceded by `android { … }`, so anchor after it.
    const androidBlock = src.search(/^android\s*\{/m);
    const searchFrom = androidBlock >= 0 ? androidBlock : 0;
    const re = /^dependencies\s*\{/m;
    const rel = src.slice(searchFrom).search(re);
    if (rel < 0) {
      throw new Error(
        "[with-detection-engine] no top-level `dependencies {` block in " +
          "app/build.gradle — the Expo prebuild template shape changed; update the " +
          "plugin."
      );
    }
    const at = searchFrom + rel;
    const braceAt = src.indexOf("{", at);
    src =
      src.slice(0, braceAt + 1) +
      `\n    ${FFMPEG_KIT_MARKER}\n    implementation '${FFMPEG_KIT_COORDINATE}'\n` +
      src.slice(braceAt + 1);
    config.modResults.contents = src;
    return config;
  });
}

function withDetectionEngine(config) {
  return withRunOnce(config, {
    plugin: (config) =>
      withPlugins(config, [
        withEngineSources,
        withBenchActivity,
        withFfmpegKitCompileDep,
        withPackageRegistration,
      ]),
    name: "with-detection-engine",
  });
}

